/**
 * Resolves the translation set to use: an explicit `data-lang` wins, then the
 * browser's language, then English. Unknown/unsupported codes fall back to English,
 * and any key missing from a non-English set falls back to the English string.
 */
export function resolveTranslations(langAttr) {
  const requested = (langAttr || (typeof navigator !== 'undefined' && navigator.language) || 'en')
    .toLowerCase()
    .split('-')[0];

  const chosen = translations[requested] || {};
  return { ...translations.en, ...chosen };
}
